#!/usr/bin/env python3
"""Generates opengl32 HLE thunks onto the fixed-function emulation layer (runtime/gfx/glemu.h).

usage: gen_gl.py <gl.h> <glemu.h> <out.cpp>

Every GL 1.x entry point in the SDK gl.h becomes a stdcall import: arguments are read from the
guest stack (doubles take two slots) and guest pointers become host pointers (the guest address
space is a flat host mapping, so client data stays valid). Functions implemented by the emulator
call emu::<name>; the rest log once that they are unsupported. Functions with hand-written thunks
(texture names, 2D/3D projection hooks, strings) are skipped.
"""
import re
import sys

SKIP = {'glGetString', 'glGetPointerv', 'glTexImage2D', 'glTexSubImage2D', 'glDeleteTextures', 'glBindTexture',
        'glGenTextures', 'glIsTexture', 'glAreTexturesResident', 'glPrioritizeTextures', 'glOrtho', 'glTexParameteri',
        'glTexParameterf', 'glFrustum', 'glDrawBuffer', 'glReadBuffer'}
SCALAR = {'GLenum': 'uint32_t', 'GLbitfield': 'uint32_t', 'GLuint': 'uint32_t', 'GLint': 'int32_t', 'GLsizei': 'int32_t',
          'GLboolean': 'uint8_t', 'GLubyte': 'uint8_t', 'GLbyte': 'int8_t', 'GLshort': 'int16_t', 'GLushort': 'uint16_t',
          'GLfloat': 'float', 'GLclampf': 'float', 'GLdouble': 'double', 'GLclampd': 'double', 'GLvoid': 'void',
          'void': 'void', 'GLchar': 'char', 'GLintptr': 'intptr_t', 'GLsizeiptr': 'intptr_t', 'GLhandleARB': 'uint32_t'}


def ctype(t):
    t = t.replace('const', ' const ').split()
    return ' '.join(SCALAR.get(w, w) for w in t)


def main():
    glh, emuh, out = sys.argv[1:4]
    emu = set(re.findall(r'\b(gl[A-Z]\w*)\s*\(', open(emuh).read()))
    protos = re.findall(r'^extern\s+(.+?)\s*\b(gl\w+)\s*\(([^)]*)\)', open(glh).read(), re.M)
    lines = ['// Generated by tools/gen_gl.py. Do not edit.', '#include "../runtime/gfx/glemu.h"',
             '#include "../runtime/win32/hle.h"', '',
             'static void glUnsupported(const char* name)', '{',
             '    static std::mutex m;', '    static std::set<std::string> seen;', '    std::lock_guard lock(m);',
             '    if (seen.insert(name).second)', '        logf("[gl] unsupported function %s (ignored)", name);', '}', '']
    lines.insert(1, '#include <mutex>\n#include <set>\n#include <string>')
    n_emu = n_stub = 0
    for ret, name, params in protos:
        if name in SKIP:
            continue
        params = params.strip()
        args, slot, ok = [], 0, True
        if params and params != 'void':
            for p in params.split(','):
                m = re.match(r'(.*?)(\w+)\s*$', p.strip())
                typ = m.group(1).strip()
                if '*' in typ:
                    args.append('(%s)(ARG(%d) ? (void*)(g_mem + ARG(%d)) : nullptr)' % (ctype(typ), slot, slot))
                    slot += 1
                    continue
                base = typ.replace('const', '').strip()
                if base in ('GLfloat', 'GLclampf'):
                    args.append('ARGF(%d)' % slot)
                    slot += 1
                elif base in ('GLdouble', 'GLclampd'):
                    args.append('rdf64(c.r[4] + 4 + 4 * %d)' % slot)
                    slot += 2
                elif base in SCALAR:
                    args.append('(%s)ARG(%d)' % (SCALAR[base], slot))
                    slot += 1
                else:
                    ok = False
                    break
        if not ok or '*' in ret:
            continue
        void = ret.strip() == 'void'
        if name in emu:
            call = 'emu::%s(%s)' % (name, ', '.join(args))
            body = call + ';' if void else 'RET(%s);' % call
            n_emu += 1
        else:
            body = 'glUnsupported("%s");%s' % (name, '' if void else ' RET(0);')
            n_stub += 1
        lines.append('WIN32API(opengl32, %s, %d) { %s }' % (name, slot, body))
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('%d emulated GL thunks, %d unsupported stubs' % (n_emu, n_stub))


main()
